import { test, expect } from './extension-fixture';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

test.describe('E2E Browser Compatibility: Inline Recovered Responses in DeepSeek Chat (Milestone 2D.4)', () => {
  test('renders inline recovery inside DeepSeek message when inline mode is enabled', async ({
    page,
    router,
    loadSidepanel,
  }) => {
    // 1. Enable inline mode via sidepanel settings
    const sidepanel = await loadSidepanel();
    await sidepanel.locator('button.tab-btn:has-text("Settings"), button.tab-btn:has-text("Настройки")').click();
    await sidepanel.waitForSelector('.recovery-presentation-card');

    // Click radio for inline mode
    await sidepanel.locator('input[type="radio"][value="inline"]').check();
    await sidepanel.waitForTimeout(300);

    // 2. Set up SSE endpoint for filtered generation
    const fixturePath = path.resolve(__dirname, '../../fixtures/deepseek/filter-stream.sse.txt');
    const sseBody = fs.readFileSync(fixturePath, 'utf8');
    router.registry.registerSseEndpoint('https://chat.deepseek.com/api/v0/chat/completion', sseBody);

    // 3. Navigate to chat session matching the fixture session id
    await page.goto('https://chat.deepseek.com/a/chat/s/sess-filter-001');

    // Inject synthetic DeepSeek assistant message node in the page DOM
    await page.evaluate(() => {
      const container = document.getElementById('chat-messages-container') || document.body;
      const msg = document.createElement('div');
      msg.id = 'msg-node-1';
      // Match remote id generated by fixture: msg_filter_001
      msg.setAttribute('data-message-id', 'msg_filter_001');

      const placeholder = document.createElement('div');
      placeholder.className = 'ds-markdown';
      placeholder.id = 'placeholder-node';
      placeholder.textContent = "I'm sorry, I cannot continue this conversation.";

      const toolbar = document.createElement('div');
      toolbar.className = 'ds-actions-toolbar';
      toolbar.id = 'native-toolbar';

      const actions = ['Copy', 'Regenerate', 'Like', 'Dislike', 'Read aloud', 'Share'];
      (window as any).__nativeClickCounts = {};
      for (const act of actions) {
        (window as any).__nativeClickCounts[act] = 0;
        const btn = document.createElement('button');
        btn.textContent = act;
        btn.className = `native-btn-${act.toLowerCase().replace(/\s+/g, '-')}`;
        btn.addEventListener('click', () => {
          (window as any).__nativeClickCounts[act]++;
        });
        toolbar.appendChild(btn);
      }

      msg.appendChild(placeholder);
      msg.appendChild(toolbar);
      container.appendChild(msg);
    });

    // 4. Trigger stream fetch from page
    await page.evaluate(async () => {
      const res = await fetch('https://chat.deepseek.com/api/v0/chat/completion', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ chat_session_id: 'sess-filter-001' }),
      });
      const reader = res.body?.getReader();
      if (reader) {
        while (true) {
          const { done } = await reader.read();
          if (done) break;
        }
      }
    });

    await page.waitForTimeout(1000);

    // 5. Verify inline recovery host was mounted inside message node
    const inlineHostExists = await page.evaluate(() => {
      const host = document.querySelector('div[data-streamarchive-inline-recovery-host]');
      return !!host;
    });
    expect(inlineHostExists).toBe(true);

    // 6. Verify placeholder was hidden and native toolbar was preserved in host DOM
    const domState = await page.evaluate(() => {
      const placeholder = document.getElementById('placeholder-node');
      const toolbar = document.getElementById('native-toolbar');
      return {
        placeholderDisplay: placeholder?.style.display,
        toolbarPresent: !!toolbar,
        toolbarButtonCount: toolbar?.querySelectorAll('button').length,
      };
    });
    expect(domState.placeholderDisplay).toBe('none');
    expect(domState.toolbarPresent).toBe(true);
    expect(domState.toolbarButtonCount).toBe(6);

    // 7. Verify native toolbar buttons remain clickable
    await page.evaluate(() => {
      const copyBtn = document.querySelector('.native-btn-copy') as HTMLButtonElement;
      const regenBtn = document.querySelector('.native-btn-regenerate') as HTMLButtonElement;
      copyBtn?.click();
      regenBtn?.click();
    });
    const clickCounts = await page.evaluate(() => (window as any).__nativeClickCounts);
    expect(clickCounts['Copy']).toBe(1);
    expect(clickCounts['Regenerate']).toBe(1);

    // 8. Test mode switch back to overlay
    await sidepanel.locator('input[type="radio"][value="overlay"]').check();
    await page.waitForTimeout(500);

    // Inline host must be unmounted and placeholder restored
    const afterOverlaySwitch = await page.evaluate(() => {
      const host = document.querySelector('div[data-streamarchive-inline-recovery-host]');
      const placeholder = document.getElementById('placeholder-node');
      return {
        hostExists: !!host,
        placeholderDisplay: placeholder?.style.display,
      };
    });
    expect(afterOverlaySwitch.hostExists).toBe(false);
    expect(afterOverlaySwitch.placeholderDisplay).toBe('');

    await sidepanel.close();
  });

  test('cleans up inline recovery immediately across route navigation', async ({
    page,
    router,
    loadSidepanel,
  }) => {
    // 1. Enable inline mode
    const sidepanel = await loadSidepanel();
    await sidepanel.locator('button.tab-btn:has-text("Settings"), button.tab-btn:has-text("Настройки")').click();
    await sidepanel.waitForSelector('.recovery-presentation-card');
    await sidepanel.locator('input[type="radio"][value="inline"]').check();
    await sidepanel.waitForTimeout(300);

    const fixturePath = path.resolve(__dirname, '../../fixtures/deepseek/filter-stream.sse.txt');
    const sseBody = fs.readFileSync(fixturePath, 'utf8');
    router.registry.registerSseEndpoint('https://chat.deepseek.com/api/v0/chat/completion', sseBody);

    // Navigate to Route A (matching fixture session id)
    await page.goto('https://chat.deepseek.com/a/chat/s/sess-filter-001');

    await page.evaluate(() => {
      const container = document.getElementById('chat-messages-container') || document.body;
      const msg = document.createElement('div');
      msg.id = 'msg-alpha';
      msg.setAttribute('data-message-id', 'msg_filter_001');

      const placeholder = document.createElement('div');
      placeholder.className = 'ds-markdown';
      placeholder.textContent = 'Filtered on Route Alpha';

      const toolbar = document.createElement('div');
      toolbar.className = 'ds-actions-toolbar';
      toolbar.appendChild(document.createElement('button'));

      msg.appendChild(placeholder);
      msg.appendChild(toolbar);
      container.appendChild(msg);
    });

    // Run generation on Route A
    await page.evaluate(async () => {
      const res = await fetch('https://chat.deepseek.com/api/v0/chat/completion', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ chat_session_id: 'sess-filter-001' }),
      });
      const reader = res.body?.getReader();
      if (reader) {
        while (true) {
          const { done } = await reader.read();
          if (done) break;
        }
      }
    });

    await page.waitForTimeout(1000);

    // Confirm inline recovery mounted on Route Alpha
    const mountedAlpha = await page.evaluate(() => {
      return !!document.querySelector('div[data-streamarchive-inline-recovery-host]');
    });
    expect(mountedAlpha).toBe(true);

    // Navigate to Route Beta (SPA navigation via pushState)
    await page.evaluate(() => {
      window.history.pushState({}, '', '/a/chat/s/sess-route-beta-2');
    });

    await page.waitForTimeout(300);

    // Inline host from Route Alpha must be unmounted immediately
    const lingeringHosts = await page.evaluate(() => {
      return document.querySelectorAll('div[data-streamarchive-inline-recovery-host]').length;
    });
    expect(lingeringHosts).toBe(0);

    await sidepanel.close();
  });
});
